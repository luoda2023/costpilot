/**
 * 全角 → 半角 转换工具
 * 
 * 自动将数字、英文字母、标点符号从全角转为半角
 * 保留中文字符不变
 */

// 全角字符 → 半角字符 映射表
const fullWidthMap = {
  // 全角数字
  '０': '0', '１': '1', '２': '2', '３': '3', '４': '4',
  '５': '5', '６': '6', '７': '7', '８': '8', '９': '9',
  // 全角英文字母 (大写)
  'Ａ': 'A', 'Ｂ': 'B', 'Ｃ': 'C', 'Ｄ': 'D', 'Ｅ': 'E',
  'Ｆ': 'F', 'Ｇ': 'G', 'Ｈ': 'H', 'Ｉ': 'I', 'Ｊ': 'J',
  'Ｋ': 'K', 'Ｌ': 'L', 'Ｍ': 'M', 'Ｎ': 'N', 'Ｏ': 'O',
  'Ｐ': 'P', 'Ｑ': 'Q', 'Ｒ': 'R', 'Ｓ': 'S', 'Ｔ': 'T',
  'Ｕ': 'U', 'Ｖ': 'V', 'Ｗ': 'W', 'Ｘ': 'X', 'Ｙ': 'Y',
  'Ｚ': 'Z',
  // 全角英文字母 (小写)
  'ａ': 'a', 'ｂ': 'b', 'ｃ': 'c', 'ｄ': 'd', 'ｅ': 'e',
  'ｆ': 'f', 'ｇ': 'g', 'ｈ': 'h', 'ｉ': 'i', 'ｊ': 'j',
  'ｋ': 'k', 'ｌ': 'l', 'ｍ': 'm', 'ｎ': 'n', 'ｏ': 'o',
  'ｐ': 'p', 'ｑ': 'q', 'ｒ': 'r', 'ｓ': 's', 'ｔ': 't',
  'ｕ': 'u', 'ｖ': 'v', 'ｗ': 'w', 'ｘ': 'x', 'ｙ': 'y',
  'ｚ': 'z',
  // 全角标点符号
  '，': ',', '。': '.', '！': '!', '？': '?', '：': ':',
  '；': ';', '“': '"', '”': '"', '‘': "'", '’': "'",
  '（': '(', '）': ')', '【': '[', '】': ']', '｛': '{',
  '｝': '}', '《': '<', '》': '>', '～': '~', '＠': '@',
  '＃': '#', '＄': '$', '％': '%', '＾': '^', '＆': '&',
  '＊': '*', '＋': '+', '＝': '=', '－': '-', '｜': '|',
  '｀': '`', '＜': '<', '＞': '>', '　': ' ', '—': '-',
  '…': '...', '·': '.', '×': 'x', '÷': '/',
}

/**
 * 全角字符正则(用于快速判断)
 */
const fullWidthRegex = new RegExp(`[${Object.keys(fullWidthMap).join('')}]`, 'g')

/**
 * 将字符串中的全角字符转为半角
 * @param {string} text - 输入文本
 * @returns {string} - 转换后的文本
 */
export function toHalfWidth(text) {
  if (!text || typeof text !== 'string') return text || ''
  return text.replace(fullWidthRegex, (ch) => fullWidthMap[ch] || ch)
}

/**
 * 判断字符串是否包含全角字符
 * @param {string} text
 * @returns {boolean}
 */
export function hasFullWidth(text) {
  if (!text) return false
  return fullWidthRegex.test(text)
}

export default { toHalfWidth, hasFullWidth }