"""
全角 → 半角 转换工具

自动将数字、英文字母、标点符号从全角转为半角
保留中文字符不变

用法:
  from packages.server.utils.format import to_half_width
  cleaned = to_half_width("Ｃ３０商品混凝土, 综合单价：４５０元/m³")
  # → "C30商品混凝土, 综合单价:450元/m³"
"""

# 全角 → 半角 映射表
_FULL_WIDTH_MAP = {
    # 全角数字
    '０': '0', '１': '1', '２': '2', '３': '3', '４': '4',
    '５': '5', '６': '6', '７': '7', '８': '8', '９': '9',
    # 全角英文字母 (大写)
    'Ａ': 'A', 'Ｂ': 'B', 'Ｃ': 'C', 'Ｄ': 'D', 'Ｅ': 'E',
    'Ｆ': 'F', 'Ｇ': 'G', 'Ｈ': 'H', 'Ｉ': 'I', 'Ｊ': 'J',
    'Ｋ': 'K', 'Ｌ': 'L', 'Ｍ': 'M', 'Ｎ': 'N', 'Ｏ': 'O',
    'Ｐ': 'P', 'Ｑ': 'Q', 'Ｒ': 'R', 'Ｓ': 'S', 'Ｔ': 'T',
    'Ｕ': 'U', 'Ｖ': 'V', 'Ｗ': 'W', 'Ｘ': 'X', 'Ｙ': 'Y',
    'Ｚ': 'Z',
    # 全角英文字母 (小写)
    'ａ': 'a', 'ｂ': 'b', 'ｃ': 'c', 'ｄ': 'd', 'ｅ': 'e',
    'ｆ': 'f', 'ｇ': 'g', 'ｈ': 'h', 'ｉ': 'i', 'ｊ': 'j',
    'ｋ': 'k', 'ｌ': 'l', 'ｍ': 'm', 'ｎ': 'n', 'ｏ': 'o',
    'ｐ': 'p', 'ｑ': 'q', 'ｒ': 'r', 'ｓ': 's', 'ｔ': 't',
    'ｕ': 'u', 'ｖ': 'v', 'ｗ': 'w', 'ｘ': 'x', 'ｙ': 'y',
    'ｚ': 'z',
    # 全角标点符号
    '，': ',', '。': '.', '！': '!', '？': '?', '：': ':',
    '；': ';', '“': '"', '”': '"', '‘': "'", '’': "'",
    '（': '(', '）': ')', '【': '[', '】': ']', '｛': '{',
    '｝': '}', '《': '<', '》': '>', '～': '~', '＠': '@',
    '＃': '#', '＄': '$', '％': '%', '＾': '^', '＆': '&',
    '＊': '*', '＋': '+', '＝': '=', '－': '-', '｜': '|',
    '｀': '`', '＜': '<', '＞': '>', '　': ' ', '—': '-',
    '…': '...', '·': '.', '×': 'x', '÷': '/',
}

# 预编译翻译表 (str.maketrans 要求 key 是单个字符, value 是单个字符)
_half_width_trans = str.maketrans(_FULL_WIDTH_MAP)


def to_half_width(text: str) -> str:
    """
    将字符串中的全角字符转为半角, 保留中文字符不变

    Args:
        text: 输入文本

    Returns:
        转换后的文本
    """
    if not text or not isinstance(text, str):
        return text or ''
    return text.translate(_half_width_trans)


def has_full_width(text: str) -> bool:
    """
    判断字符串是否包含全角字符

    Args:
        text: 输入文本

    Returns:
        是否包含全角字符
    """
    if not text:
        return False
    for ch in text:
        if ord(ch) > 0xFF00 and ord(ch) < 0xFF5F:
            return True
        if ch in _FULL_WIDTH_MAP:
            return True
    return False