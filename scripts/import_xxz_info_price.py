def insert(db, spec_name, items, remark=""):
    """批量插入数据到t_region_info_price表"""
    spec_id = db.execute(text("SELECT id FROM t_specialty WHERE name = :n"), {'n': spec_name}).scalar()
    if not spec_id:
        print(f"  [ERROR] 专业不存在: {spec_name}")
        return
    
    count = 0
    for item in items:
        # 插入到价格库
        db.execute(text("""
            INSERT INTO t_price_unit 
            (specialty_id, item_name, unit, price, region, source_file, remark)
            VALUES (:sid, :name, :unit, :price, :region, :source, :remark)
        """), {
            'sid': spec_id,
            'name': item[0],
            'unit': item[1],
            'price': f"{item[2]} / {item[3]}",  # 5月价 / 6月价
            'region': REGION,
            'source': SOURCE_FILE,
            'remark': f"{remark} {item[4]}" if len(item) > 4 else remark
        })
        count += 1
    
    print(f"  [OK] {spec_name}: 插入 {count} 条")
    return count


